export function applyLmsTranslations() {
  let code = fs.readFileSync(stringsPath, 'utf8');

  for (const [loc, dict] of Object.entries(translations)) {
    // For each key in dict, replace or insert in the locale object
    for (const [k, v] of Object.entries(dict)) {
      // Check if locale contains this key
      const keyPattern = new RegExp(`"${loc}":\\s*{[^}]*?${JSON.stringify(k)}:`, 's');
      // A cleaner way is searching for `"${loc}": {`
      const locPattern = `"${loc}": {`;
      const locIdx = code.indexOf(locPattern);
      if (locIdx === -1) continue;

      const nextLocIdx = code.indexOf('\n    },', locIdx);
      const section = code.slice(locIdx, nextLocIdx);

      const existingKeyIdx = section.indexOf(`"${k}":`);
      if (existingKeyIdx !== -1) {
        // Replace line
        const endOfLine = section.indexOf('\n', existingKeyIdx);
        const oldLine = section.slice(existingKeyIdx, endOfLine);
        const newLine = `"${k}": ${JSON.stringify(v)},`;
        const updatedSection = section.replace(oldLine, newLine);
        code = code.slice(0, locIdx) + updatedSection + code.slice(nextLocIdx);
      } else {
        // Insert right after `"${loc}": {`
        const insertPos = locIdx + locPattern.length;
        const toInsert = `\n        ${JSON.stringify(k)}: ${JSON.stringify(v)},`;
        code = code.slice(0, insertPos) + toInsert + code.slice(insertPos);
      }
    }
  }

  fs.writeFileSync(stringsPath, code, 'utf8');
}

