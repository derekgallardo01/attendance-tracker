// Attendance PDF generation (WS-cert stage 1: the free Session Report).
//
// Split in two so the logic stays testable:
//   • buildReportModel(...)  — PURE. Normalizes attendance data into a render
//     model (rows, totals, meta, verification code). Fully unit-tested.
//   • renderReportPdf(model) — thin pdfkit pass that draws the model to bytes.
//
// A Unicode font (Noto Sans) is embedded when present so attendee names in
// Cyrillic / Greek / Vietnamese / accented Latin render correctly instead of as
// tofu boxes — the service now has users in many countries. CJK / Arabic need
// their own fonts and are a follow-up (see the cert spec).
const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const PDFDocument = require('pdfkit');
const { getPdfLabels, localizeStatus } = require('./i18n');

const FONT_PATH = path.join(__dirname, '..', '..', 'assets', 'fonts', 'NotoSans-Regular.ttf');
// Resolve once at load; if the font is somehow missing we fall back to pdfkit's
// built-in Helvetica rather than crashing (Latin-only, but never blank).
const UNICODE_FONT = fs.existsSync(FONT_PATH) ? FONT_PATH : null;

const DEFAULT_FOOTER = 'Generated by attendancetracker.dev';

// ─────────────────────────── pure helpers ───────────────────────────
function toDate(v) {
  if (!v) return null;
  const d = v instanceof Date ? v : new Date(v);
  return Number.isNaN(d.getTime()) ? null : d;
}

function durationMin(join, leave, fallbackEnd) {
  const j = toDate(join);
  if (!j) return 0;
  // Certificates grant CREDIT — never credit time that hasn't happened yet.
  // fallbackEnd is usually the SCHEDULED event end, so for a still-present
  // attendee (leave null) cap the end at `now`: generating certs 10 minutes
  // into a 2-hour session used to issue 2-hour credits. An entirely unknown
  // end still credits 0 (under-credit beats inventing time).
  const l0 = toDate(leave) || toDate(fallbackEnd);
  if (!l0) return 0;
  const now = new Date();
  const l = l0 > now ? now : l0;
  return Math.max(0, Math.round((l - j) / 60000));
}

function fmtDuration(min) {
  const m = Math.max(0, Math.round(min || 0));
  if (m < 60) return `${m}m`;
  const h = Math.floor(m / 60);
  const r = m % 60;
  return r ? `${h}h ${String(r).padStart(2, '0')}m` : `${h}h`;
}

function getTzAbbr(tz, locale, date = new Date()) {
  if (!tz) return null;
  try {
    const parts = new Intl.DateTimeFormat(locale || 'en-US', {
      timeZone: tz,
      timeZoneName: 'short',
    }).formatToParts(date);
    const tzPart = parts.find((p) => p.type === 'timeZoneName');
    return tzPart ? tzPart.value : null;
  } catch (_) {
    return null;
  }
}

// Time in the meeting's timezone when given, formatted for the locale. Best-effort:
// a bad tz string falls back rather than throwing.
function fmtTime(v, tz, locale) {
  const d = toDate(v);
  if (!d) return '—';
  const loc = locale || 'en-US';
  try {
    return new Intl.DateTimeFormat(loc, {
      hour: 'numeric', minute: '2-digit', timeZone: tz || undefined,
    }).format(d);
  } catch (_) {
    return new Intl.DateTimeFormat('en-US', { hour: 'numeric', minute: '2-digit' }).format(d);
  }
}

function fmtDate(v, tz, locale) {
  const d = toDate(v);
  if (!d) return '—';
  const loc = locale || 'en-US';
  try {
    return new Intl.DateTimeFormat(loc, {
      weekday: 'short', year: 'numeric', month: 'short', day: 'numeric', timeZone: tz || undefined,
    }).format(d);
  } catch (_) {
    return new Intl.DateTimeFormat('en-US', { year: 'numeric', month: 'short', day: 'numeric' }).format(d);
  }
}

function statusOf(p, locale) {
  let raw = 'Present';
  if (p.present) {
    raw = 'Present';
  } else if (p.present === false) {
    if (p.status && !/^(present|true)$/i.test(String(p.status).trim())) {
      const s = String(p.status).trim();
      if (/^absent$/i.test(s)) raw = 'Absent';
      else if (/^excused$/i.test(s)) raw = 'Excused';
      else raw = s;
    } else if (toDate(p.leaveTime ?? p.leaveTimeISO)) {
      raw = 'Left';
    } else {
      raw = 'Absent';
    }
  } else if (p.status) {
    const s = String(p.status).trim();
    if (/^absent$/i.test(s)) raw = 'Absent';
    else if (/^excused$/i.test(s)) raw = 'Excused';
    else raw = s;
  } else {
    raw = toDate(p.leaveTime ?? p.leaveTimeISO) ? 'Left' : 'Present';
  }
  return localizeStatus(raw, locale);
}

// A short, stable, human-quotable code so a report can be referenced later.
// Deterministic (no randomness) → the same meeting always yields the same code,
// and it becomes the key for the public verify page in a later stage.
function verificationCode(seed) {
  const h = crypto.createHash('sha1').update(String(seed || 'x')).digest('hex').slice(0, 8).toUpperCase();
  return `AT-${h}`;
}

function calcActiveMins(p, join, leave, fallbackEnd, referenceTime) {
  if (typeof p?.durationMs === 'number' && p.durationMs >= 0) {
    return Math.round(p.durationMs / 60000);
  }
  if (typeof p?.durationMin === 'number' && p.durationMin >= 0) {
    return Math.round(p.durationMin);
  }
  if (join && !leave && (referenceTime || p?.present)) {
    const end = referenceTime || new Date();
    return durationMin(join, end, fallbackEnd);
  }
  return durationMin(join, leave, fallbackEnd);
}

// PURE: normalize whatever attendance shape we were handed (persisted Firestore
// participants use joinTime/leaveTime Dates; the live client payload uses
// joinTimeISO/leaveTimeISO strings) into a flat render model.
function buildReportModel({ meeting = {}, attendees = [], options = {} } = {}) {
  const tz = meeting.timezone || null;
  const locale = meeting.locale || options.locale || 'en';
  const fallbackEnd = meeting.endTime || null;
  const labels = getPdfLabels(locale);

  const rows = (attendees || []).map((p) => {
    const join = p.joinTime ?? p.joinTimeISO ?? null;
    const leave = p.leaveTime ?? p.leaveTimeISO ?? null;
    const mins = calcActiveMins(p, join, leave, fallbackEnd, options.now || meeting.exportedAt);
    return {
      name: (p.displayName || p.name || 'Unknown').toString(),
      email: (p.email || '').toString(),
      joined: fmtTime(join, tz, locale),
      left: leave ? fmtTime(leave, tz, locale) : '—',
      active: fmtDuration(mins),
      activeMin: mins,
      status: statusOf(p, locale),
    };
  });

  const presentCount = (attendees || []).filter((p) => {
    if (p.present === false && !toDate(p.leaveTime ?? p.leaveTimeISO)) return false;
    const st = String(p.status || '');
    if (/absent|excused|ausente|faltou/i.test(st)) return false;
    const s = statusOf(p);
    return s !== 'Absent' && s !== 'Excused' && !/absent|excused|ausente|faltou/i.test(s);
  }).length;
  const brandName = options.brand && options.brand.name ? String(options.brand.name) : null;
  const tzAbbr = getTzAbbr(tz, locale, toDate(meeting.startTime || meeting.date) || new Date());
  const cols = [labels.columns.name, labels.columns.email, labels.columns.joined, labels.columns.left, labels.columns.active, labels.columns.status];
  const colLabels = {
    ...labels.columns,
    joined: tzAbbr ? `${labels.columns.joined} (${tzAbbr})` : labels.columns.joined,
    left: tzAbbr ? `${labels.columns.left} (${tzAbbr})` : labels.columns.left,
  };

  return {
    title: (meeting.title || 'Google Meet').toString(),
    reportTitle: labels.reportTitle,
    date: fmtDate(meeting.startTime || meeting.date, tz, locale) + (tzAbbr ? ` (${tzAbbr})` : ''),
    datePrefix: labels.dateLabel,
    timezone: tz,
    tzAbbr,
    host: meeting.host ? String(meeting.host) : null,
    hostPrefix: labels.hostLabel,
    durationLabel: meeting.startTime && meeting.endTime
      ? fmtDuration(durationMin(meeting.startTime, meeting.endTime))
      : null,
    durationPrefix: labels.durationLabel,
    columns: cols,
    colLabels,
    rows,
    summary: {
      present: presentCount,
      total: rows.length,
      text: labels.summaryFormat(presentCount, rows.length),
    },
    footer: brandName ? `${brandName} · via attendancetracker.dev` : DEFAULT_FOOTER,
    verificationCode: verificationCode(
      options.verifySeed || `${meeting.conferenceId || ''}|${meeting.title || ''}|${meeting.startTime || ''}`,
    ),
  };
}

// ─────────────────────────── renderer ───────────────────────────
/* istanbul ignore next: exercised end-to-end in tests via the %PDF assertion,
   but the per-primitive pdfkit draw calls aren't worth line-by-line coverage. */
function renderReportPdf(model) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `Attendance — ${model.title}` } });
      if (UNICODE_FONT) doc.registerFont('body', UNICODE_FONT);
      const font = UNICODE_FONT ? 'body' : 'Helvetica';
      const chunks = [];
      doc.on('data', (c) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const left = doc.page.margins.left;
      const right = doc.page.width - doc.page.margins.right;
      const width = right - left;

      // Header
      doc.font(font).fontSize(20).fillColor('#111827').text(model.reportTitle || 'Attendance Report', left, 50);
      doc.moveDown(0.2);
      doc.fontSize(13).fillColor('#374151').text(model.title, { width });
      doc.moveDown(0.4);
      doc.fontSize(10).fillColor('#6b7280');
      const dateText = model.date && `${model.datePrefix ? model.datePrefix + ': ' : 'Date: '}${model.date}`;
      const hostText = model.host && `${model.hostPrefix ? model.hostPrefix + ': ' : 'Host: '}${model.host}`;
      const durText = model.durationLabel && `${model.durationPrefix ? model.durationPrefix + ': ' : 'Duration: '}${model.durationLabel}`;
      const metaBits = [dateText, hostText, durText].filter(Boolean);
      if (metaBits.length) doc.text(metaBits.join('     '), { width });
      doc.moveDown(0.2);
      doc.fillColor('#111827').fontSize(11).text(model.summary.text, { width });
      doc.moveDown(0.6);

      // Table
      const cols = [
        { key: 'name', label: model.colLabels?.name || 'Name', w: 0.25 },
        { key: 'email', label: model.colLabels?.email || 'Email', w: 0.27 },
        { key: 'joined', label: model.colLabels?.joined || 'Joined', w: 0.12 },
        { key: 'left', label: model.colLabels?.left || 'Left', w: 0.12 },
        { key: 'active', label: model.colLabels?.active || 'Active', w: 0.11 },
        { key: 'status', label: model.colLabels?.status || 'Status', w: 0.13 },
      ];
      const xs = [];
      let acc = left;
      for (const c of cols) { xs.push(acc); acc += c.w * width; }

      const drawRow = (vals, { bold, y }) => {
        doc.font(font).fontSize(9).fillColor(bold ? '#111827' : '#374151');
        cols.forEach((c, i) => {
          doc.text(String(vals[c.key] ?? ''), xs[i] + 2, y, { width: c.w * width - 4, lineBreak: false, ellipsis: true });
        });
      };

      let y = doc.y;
      drawRow(Object.fromEntries(cols.map((c) => [c.key, c.label])), { bold: true, y });
      y += 14;
      doc.moveTo(left, y - 2).lineTo(right, y - 2).lineWidth(0.5).strokeColor('#d1d5db').stroke();
      y += 4;

      for (const r of model.rows) {
        if (y > doc.page.height - doc.page.margins.bottom - 40) { doc.addPage(); y = doc.page.margins.top; }
        drawRow(r, { bold: false, y });
        y += 13;
      }

      // Footer band on every page
      const range = doc.bufferedPageRange();
      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);
        const fy = doc.page.height - doc.page.margins.bottom + 8;
        doc.font(font).fontSize(8).fillColor('#9ca3af')
          .text(`${model.footer}   ·   Verification: ${model.verificationCode}`,
            left, fy, { width, align: 'center', lineBreak: false });
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

// ─────────────────── per-attendee certificates (Pro) ───────────────────
// PURE: one certificate model per attendee who was actually present (absentees
// and excused are never certified). creditHours, when given, is a fixed value
// applied to all (typical for a fixed-length course/CLE session); otherwise the
// certificate states the individual's active duration.
function buildCertificateModels({ meeting = {}, attendees = [], options = {} } = {}) {
  const tz = meeting.timezone || null;
  const locale = meeting.locale || options.locale || 'en';
  const fallbackEnd = meeting.endTime || null;
  const session = (meeting.title || 'Google Meet').toString();
  const dateLabel = fmtDate(meeting.startTime || meeting.date, tz, locale);
  const issuer = options.issuer ? String(options.issuer) : (meeting.host ? String(meeting.host) : null);
  const courseCode = options.courseCode ? String(options.courseCode) : null;
  const fixedCredit = Number(options.creditHours);
  const brandName = options.brand && options.brand.name ? String(options.brand.name) : null;
  const footer = brandName ? `${brandName} · via attendancetracker.dev` : DEFAULT_FOOTER;

  return (attendees || [])
    .filter((p) => {
      if (p.present === false && !toDate(p.leaveTime ?? p.leaveTimeISO)) return false;
      const st = String(p.status || '');
      if (/absent|excused|ausente|faltou/i.test(st)) return false;
      const s = statusOf(p);
      return s !== 'Absent' && s !== 'Excused' && !/absent|excused|ausente|faltou/i.test(s);
    })
    .map((p) => {
      const join = p.joinTime ?? p.joinTimeISO ?? null;
      const leave = p.leaveTime ?? p.leaveTimeISO ?? null;
      const mins = calcActiveMins(p, join, leave, fallbackEnd, options.now || meeting.exportedAt);
      return {
        name: (p.displayName || p.name || 'Attendee').toString(),
        session,
        dateLabel,
        durationLabel: fmtDuration(mins),
        creditHoursLabel: Number.isFinite(fixedCredit) && fixedCredit > 0
          ? `${fixedCredit} credit hour${fixedCredit === 1 ? '' : 's'}`
          : null,
        courseCode,
        issuer,
        footer,
        verificationCode: verificationCode(
          options.verifySeed
            ? `${options.verifySeed}|${p.email || p.displayName || ''}`
            : `${meeting.conferenceId || ''}|${p.email || p.displayName || ''}|${meeting.title || ''}`,
        ),
      };
    });
}

/* istanbul ignore next: layout primitives — exercised via the %PDF + page-count
   assertions in the tests, not worth per-draw-call coverage. */
function drawCertificate(doc, font, m) {
  const w = doc.page.width;
  const h = doc.page.height;
  // Double border
  doc.lineWidth(3).strokeColor('#1d4ed8').rect(24, 24, w - 48, h - 48).stroke();
  doc.lineWidth(0.75).strokeColor('#93c5fd').rect(34, 34, w - 68, h - 68).stroke();

  const cx = w / 2;
  doc.font(font).fillColor('#1e3a8a').fontSize(30).text('Certificate of Attendance', 0, 90, { width: w, align: 'center' });
  doc.fillColor('#374151').fontSize(13).text('This certifies that', 0, 150, { width: w, align: 'center' });

  // Dynamic font downscaling for long attendee names (>35 chars or width > w - 80)
  let nameFontSize = 28;
  const maxNameWidth = w - 80;
  const nameStr = m.name || '';
  if (nameStr.length > 35) {
    nameFontSize = 22;
  }
  while (nameFontSize > 14 && doc.font(font).fontSize(nameFontSize).widthOfString(nameStr) > maxNameWidth) {
    nameFontSize -= 1;
  }
  doc.fillColor('#111827').fontSize(nameFontSize).text(nameStr, 0, 180, { width: w, align: 'center' });

  const attendedY = Math.max(232, doc.y + 12);
  doc.fillColor('#374151').fontSize(13).text('attended', 0, attendedY, { width: w, align: 'center' });

  // Dynamic font downscaling for long session titles (>45 chars or width > w - 120)
  let sessionFontSize = 18;
  const maxSessionWidth = w - 120;
  const sessionStr = m.session || '';
  if (sessionStr.length > 45) {
    sessionFontSize = 15;
  }
  while (sessionFontSize > 11 && doc.font(font).fontSize(sessionFontSize).widthOfString(sessionStr) > maxSessionWidth) {
    sessionFontSize -= 1;
  }
  const sessionY = Math.max(258, doc.y + 10);
  doc.fillColor('#111827').fontSize(sessionFontSize).text(sessionStr, 60, sessionY, { width: maxSessionWidth, align: 'center' });

  const detail = [
    m.dateLabel && `on ${m.dateLabel}`,
    m.creditHoursLabel ? `for ${m.creditHoursLabel}` : `for ${m.durationLabel}`,
  ].filter(Boolean).join('   ·   ');
  const detailY = Math.max(300, doc.y + 16);
  doc.fillColor('#374151').fontSize(13).text(detail, 0, detailY, { width: w, align: 'center' });
  if (m.courseCode) {
    const refY = Math.max(326, doc.y + 8);
    doc.fillColor('#6b7280').fontSize(11).text(`Reference: ${m.courseCode}`, 0, refY, { width: w, align: 'center' });
  }

  // Signature + issuer
  const sigY = h - 130;
  doc.lineWidth(0.75).strokeColor('#9ca3af').moveTo(cx - 130, sigY).lineTo(cx + 130, sigY).stroke();
  doc.fillColor('#374151').fontSize(11).text(m.issuer || 'Issued by the meeting host', 0, sigY + 6, { width: w, align: 'center' });

  // Footer band — includes the public verification URL so a registrar can confirm.
  doc.fillColor('#9ca3af').fontSize(8)
    .text(`${m.footer}   ·   Verify at attendancetracker.dev/verify.html?c=${m.verificationCode}`, 0, h - 60, { width: w, align: 'center' });
}

/* istanbul ignore next: thin pdfkit shell, asserted structurally in tests. */
function renderCertificatesPdf(models) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 0 });
      if (UNICODE_FONT) doc.registerFont('body', UNICODE_FONT);
      const font = UNICODE_FONT ? 'body' : 'Helvetica';
      const chunks = [];
      doc.on('data', (c) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const list = models && models.length ? models : [];
      if (!list.length) {
        doc.font(font).fontSize(14).fillColor('#374151').text('No eligible attendees to certify.', 60, 60);
      } else {
        list.forEach((m, i) => { if (i > 0) doc.addPage(); drawCertificate(doc, font, m); });
      }
      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

// ─────────────── Institutional / School Quote PDF ("Ask my school to pay") ───────────────
// PURE: builds a structured quote model a teacher can forward to their principal,
// department chair, or business office for P-card checkout or PO approval.
function buildQuoteModel({
  teacherName = null,
  teacherEmail = '',
  domain = '',
  schoolName = null,
  department = null,
  recommendedPlan = null,
  usage = {},
  issuedAt = new Date(),
} = {}) {
  const issuedDate = toDate(issuedAt) || new Date();
  const validUntilDate = new Date(issuedDate.getTime() + 30 * 86400000);
  const emailClean = String(teacherEmail || '').trim();
  const domainClean = String(domain || (emailClean.includes('@') ? emailClean.split('@')[1] : '') || '').trim().toLowerCase();
  const resolvedSchool = (schoolName && String(schoolName).trim())
    || (domainClean && domainClean !== 'gmail.com' ? domainClean : 'School / Department');
  const domainTeachers = Math.max(1, Number(usage.domainTeachers) || 1);
  const classesTracked = Math.max(0, Number(usage.classesTracked) || 0);
  const totalStudents = Math.max(0, Number(usage.totalStudents) || 0);

  const planKey = recommendedPlan
    || (domainTeachers >= 50 ? 'quote' : (domainTeachers >= 10 ? 'institution' : 'department'));
  const quoteNumber = verificationCode(`${emailClean}|${domainClean}|${issuedDate.toISOString().slice(0, 10)}`).replace(/^AT-/, 'QT-');

  const plans = [
    {
      key: 'individual_annual',
      name: 'Educator Annual Pass (1 Teacher)',
      price: '$19 / year',
      amountUsd: 19,
      description: 'Unlimited class size, automatic Google Sheets export, multi-session gradebooks, and student attendance certificates for 1 educator.',
      recommended: planKey === 'individual_annual',
    },
    {
      key: 'department',
      name: 'Department Plan (Up to 10 Teachers)',
      price: '$79 / year',
      amountUsd: 79,
      description: `Covers up to 10 educators on ${domainClean || 'your school domain'} (~$7.90/teacher/year). Includes shared attendance history and LMS gradebook exports.`,
      recommended: planKey === 'department',
    },
    {
      key: 'institution',
      name: 'School / Institution Site License (Unlimited Teachers)',
      price: '$149 / year',
      amountUsd: 149,
      description: `Site-wide Pro access for every educator on @${domainClean || 'school.edu'}. Includes W-9 / vendor onboarding and PO / invoice support.`,
      recommended: planKey === 'institution' || planKey === 'quote',
    },
  ];

  return {
    quoteNumber,
    issuedDate: fmtDate(issuedDate, 'UTC', 'en-US'),
    validUntilDate: fmtDate(validUntilDate, 'UTC', 'en-US'),
    teacherName: teacherName ? String(teacherName).trim() : null,
    teacherEmail: emailClean,
    domain: domainClean,
    schoolName: resolvedSchool,
    department: department ? String(department).trim() : null,
    recommendedPlan: planKey,
    usage: {
      classesTracked,
      totalStudents,
      domainTeachers,
    },
    plans,
    checkoutUrl: `https://attendancetracker.dev/pricing.html?domain=${encodeURIComponent(domainClean)}&quote=${encodeURIComponent(quoteNumber)}`,
    contactEmail: 'derek@attendancetracker.dev',
  };
}

